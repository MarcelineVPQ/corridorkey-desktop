#!/usr/bin/env node
// node_modules is what package-lock.json says (release review 2026-10-28 #4): tools/release.sh bundles whatever is in
// node_modules, and THIRD_PARTY_NOTICES is written from the lock, so a pull that bumps the lock without `npm ci`
// would ship the old copy under the new copy's notice. Fails when a locked package is missing (unless the lock marks
// it optional: another system's build), installed at another version, or when node_modules holds a package the lock
// doesn't list.
//   node tools/check_node_modules.mjs [APP]    exit 1 with each difference (release.sh step 1)
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The packages installed under `dir`/node_modules, recursively (nested node_modules too), as lock keys. */
export function installed(app, dir = "") {
  const nm = join(app, dir, "node_modules");
  if (!existsSync(nm)) return [];
  const out = [];
  // loop: NOT-WORTH — one node_modules folder's entries (a few hundred at the top), once per release
  for (const n of readdirSync(nm)) {
    if (n.startsWith(".")) continue;
    // loop: NOT-WORTH — a scope's few packages
    const names = n.startsWith("@") ? readdirSync(join(nm, n)).map((s) => `${n}/${s}`) : [n];
    // loop: NOT-WORTH — the packages in this entry
    for (const name of names) {
      const key = join(dir, "node_modules", name);
      if (!existsSync(join(app, key, "package.json")) || !statSync(join(app, key)).isDirectory()) continue;
      out.push(key, ...installed(app, key));
    }
  }
  return out;
}

/** The differences between package-lock.json's `packages` and node_modules in `app`. */
export function checkNodeModules(app) {
  const lock = JSON.parse(readFileSync(join(app, "package-lock.json"), "utf8")).packages ?? {};
  const out = [];
  // loop: NOT-WORTH — the lock's packages (~540), once per release
  for (const [key, p] of Object.entries(lock)) {
    if (!key.startsWith("node_modules/") && !key.includes("/node_modules/")) continue;
    if (p.link) continue;
    const pj = join(app, key, "package.json");
    if (!existsSync(pj)) {
      if (!p.optional) out.push(`${key}: in the lock (${p.version}), not installed`);
      continue;
    }
    const v = JSON.parse(readFileSync(pj, "utf8")).version;
    if (v !== p.version) out.push(`${key}: installed ${v}, the lock says ${p.version}`);
  }
  // loop: NOT-WORTH — the installed packages, once per release
  for (const key of installed(app)) if (!lock[key]) out.push(`${key}: installed, not in the lock`);
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const app = process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), "..");
  const diff = checkNodeModules(app);
  if (diff.length) {
    console.log(`node_modules isn't package-lock.json (run: npx -y npm@10.9.2 ci):\n${diff.join("\n")}`);
    process.exit(1);
  }
  console.log("check_node_modules: node_modules is package-lock.json");
}
