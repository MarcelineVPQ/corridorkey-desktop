//! Windows only: `corridorkey run`'s stop path end to end (final review 2026-10-28 N11; before, only `ask_to_stop` and
//! `script_status` had tests and the rest was a manual VM run). The real `corridorkey` binary runs a stub script runner
//! (this test program itself, as `CK_APP`, in stub mode) and gets real console events from GenerateConsoleCtrlEvent:
//!  - Ctrl+Break to its process group: a `stop` line reaches the runner, which ends as the app's runner does (130);
//!  - Ctrl+C in a console of its own (sent by a helper, this program again, attached to that console): the same;
//!  - a second Ctrl+Break: the CLI exits 143 at once and the runner ends with it (its job object).
//!
//! Its own harness (Cargo.toml `harness = false`): the program is also the stub and the helper, which libtest's
//! argument parsing would refuse. Elsewhere it does nothing. Runs in the Windows workflow's `cargo test`
//! (.github/workflows/windows.yml). The console close's 4.5 s wait (CTRL_CLOSE_EVENT) can't be generated by a program.

fn main() {
    #[cfg(windows)]
    win::main();
    #[cfg(not(windows))]
    println!("run_stop_windows: Windows only, nothing to run here");
}

#[cfg(windows)]
mod win {
    use std::io::{BufRead, BufReader, Read};
    use std::os::windows::process::CommandExt;
    use std::process::{Child, Command, Stdio};
    use std::sync::mpsc::{channel, Receiver};
    use std::time::{Duration, Instant};

    #[link(name = "kernel32")]
    extern "system" {
        fn GenerateConsoleCtrlEvent(event: u32, group: u32) -> i32;
        fn FreeConsole() -> i32;
        fn AttachConsole(pid: u32) -> i32;
        fn SetConsoleCtrlHandler(handler: Option<unsafe extern "system" fn(u32) -> i32>, add: i32) -> i32;
    }
    const CTRL_C_EVENT: u32 = 0;
    const CTRL_BREAK_EVENT: u32 = 1;
    const CREATE_NEW_CONSOLE: u32 = 0x0000_0010;
    const CREATE_NEW_PROCESS_GROUP: u32 = 0x0000_0200;
    /// stub mode: "obey" (a `stop` line ends it with 130, as the app's runner) or "ignore" (it keeps running)
    const STUB: &str = "CK_TEST_STUB_RUNNER";
    /// helper mode: the pid whose console gets a Ctrl+C
    const SEND_CTRL_C: &str = "CK_TEST_SEND_CTRL_C";

    pub fn main() {
        if let Ok(mode) = std::env::var(STUB) {
            stub(&mode);
        }
        if let Ok(pid) = std::env::var(SEND_CTRL_C) {
            send_ctrl_c(pid.parse().expect("a pid"));
        }
        let tests: [(&str, fn()); 3] = [
            ("ctrl_break_asks_the_runner_to_stop", ctrl_break_asks_the_runner_to_stop),
            ("ctrl_c_in_its_own_console_asks_the_runner_to_stop", ctrl_c_in_its_own_console_asks_the_runner_to_stop),
            ("a_second_ctrl_break_ends_the_run_and_its_runner", a_second_ctrl_break_ends_the_run_and_its_runner),
        ];
        // loop: NOT-WORTH — three tests, in order (each owns console events: never in parallel)
        for (name, t) in tests {
            println!("test {name} ...");
            t();
            println!("test {name} ... ok");
        }
    }

    /// The app's script runner, as far as `corridorkey run` sees it: started with `--ck-headless run FILE` and
    /// CK_HEADLESS_STOP=stdin, says it is ready, and reads its stdin for the `stop` line.
    fn stub(mode: &str) -> ! {
        let args: Vec<String> = std::env::args().collect();
        assert!(args.iter().any(|a| a == "run"), "the runner is started to run a script: {args:?}");
        assert_eq!(std::env::var("CK_HEADLESS_STOP").as_deref(), Ok("stdin"));
        println!("stub: ready {}", std::process::id());
        let stdin = std::io::stdin();
        // loop: SERIAL-REQUIRED — the runner's stdin, a line at a time [bounded: the CLI's pipe closes when it ends]
        for line in stdin.lock().lines() {
            if line.as_deref().is_ok_and(|l| l.trim() == "stop") {
                if mode == "obey" {
                    eprintln!("stub: cancelled");
                    std::process::exit(130);
                }
                println!("stub: stop ignored");
            }
        }
        // the CLI's end closed the pipe; a runner that ignores stops stays until killed (its job object ends it)
        if mode == "ignore" {
            // loop: SERIAL-REQUIRED — stays up so the test sees the job object end it [bounded: 60 s]
            std::thread::sleep(Duration::from_secs(60));
        }
        std::process::exit(3);
    }

    /// The helper: Ctrl+C to every process on `pid`'s console (the CLI, which handles it; the runner, in a group of its
    /// own, ignores Ctrl+C), never to the test's own console.
    fn send_ctrl_c(pid: u32) -> ! {
        // SAFETY: documented kernel32 calls; this process only sends the event and exits
        let ok =
            unsafe { FreeConsole() != 0 && AttachConsole(pid) != 0 && SetConsoleCtrlHandler(None, 1) != 0 && GenerateConsoleCtrlEvent(CTRL_C_EVENT, 0) != 0 };
        std::process::exit(if ok { 0 } else { 1 });
    }

    /// `corridorkey run` on a dummy script with this program as the app (stub `mode`), started with `flags`.
    fn cli(mode: &str, flags: u32) -> (Child, Receiver<String>, std::thread::JoinHandle<String>) {
        let script = std::env::temp_dir().join(format!("ck-run-stop-{}.ckcmd", std::process::id()));
        std::fs::write(&script, "info\n").unwrap();
        let mut child = Command::new(env!("CARGO_BIN_EXE_corridorkey"))
            .args(["run", script.to_str().unwrap()])
            .env("CK_APP", std::env::current_exe().unwrap())
            .env_remove("CK_APP_ENTRY")
            .env(STUB, mode)
            .creation_flags(flags)
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap();
        let (tx, rx) = channel();
        let out = child.stdout.take().unwrap();
        // loop: SERIAL-REQUIRED — the CLI's stdout (the stub's lines), one reader [bounded: ends with the pipe]
        std::thread::spawn(move || {
            // loop: SERIAL-REQUIRED — a line at a time [bounded: the pipe closes when the CLI and the stub end]
            for l in BufReader::new(out).lines().map_while(Result::ok) {
                let _ = tx.send(l);
            }
        });
        let mut err = child.stderr.take().unwrap();
        // loop: SERIAL-REQUIRED — the CLI's stderr, read whole [bounded: ends with the pipe]
        let err = std::thread::spawn(move || {
            let mut s = String::new();
            let _ = err.read_to_string(&mut s);
            s
        });
        (child, rx, err)
    }

    /// The next stdout line starting with `prefix`, within 20 s.
    fn line(rx: &Receiver<String>, prefix: &str) -> String {
        let end = Instant::now() + Duration::from_secs(20);
        // loop: SERIAL-REQUIRED — waits for one line [bounded: 20 s]
        loop {
            let left = end.saturating_duration_since(Instant::now());
            match rx.recv_timeout(left) {
                Ok(l) if l.starts_with(prefix) => return l,
                Ok(_) => {}
                Err(e) => panic!("no {prefix:?} line within 20 s ({e})"),
            }
        }
    }

    /// The CLI's exit code, within 20 s (killed and failed past it).
    fn exit_code(child: &mut Child) -> i32 {
        let end = Instant::now() + Duration::from_secs(20);
        // loop: SERIAL-REQUIRED — a 50 ms poll [bounded: 20 s, then kill]
        loop {
            if let Some(s) = child.try_wait().unwrap() {
                return s.code().unwrap();
            }
            if Instant::now() >= end {
                let _ = child.kill();
                panic!("corridorkey run didn't end within 20 s of the stop");
            }
            std::thread::sleep(Duration::from_millis(50));
        }
    }

    /// The stub is up and the CLI's console handler installed (it is installed right after the stub starts).
    fn ready(rx: &Receiver<String>) -> u32 {
        let l = line(rx, "stub: ready ");
        std::thread::sleep(Duration::from_millis(1000));
        l.trim_start_matches("stub: ready ").trim().parse().unwrap()
    }

    fn ctrl_break_asks_the_runner_to_stop() {
        let (mut c, rx, err) = cli("obey", CREATE_NEW_PROCESS_GROUP);
        ready(&rx);
        // SAFETY: a documented kernel32 call; the group is the CLI's own (CREATE_NEW_PROCESS_GROUP), not the test's
        assert!(unsafe { GenerateConsoleCtrlEvent(CTRL_BREAK_EVENT, c.id()) } != 0);
        let code = exit_code(&mut c);
        let err = err.join().unwrap();
        assert_eq!(code, 130, "the runner's own stop code: {err}");
        assert!(err.contains("stub: cancelled"), "the stop line reached the runner: {err}");
    }

    fn ctrl_c_in_its_own_console_asks_the_runner_to_stop() {
        // a console of its own: the Ctrl+C reaches the CLI (and the runner, which ignores it), never this test or cargo.
        // A launcher that started this test in a process group of its own left Ctrl+C ignored, and the CLI would inherit
        // that: processing turned back on first (only this test's own console could send it one, and nothing does)
        // SAFETY: a documented kernel32 call (NULL handler, FALSE: Ctrl+C processed normally)
        unsafe { SetConsoleCtrlHandler(None, 0) };
        let (mut c, rx, err) = cli("obey", CREATE_NEW_CONSOLE);
        ready(&rx);
        let helper = Command::new(std::env::current_exe().unwrap())
            .env(SEND_CTRL_C, c.id().to_string())
            .env_remove(STUB)
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .unwrap();
        assert!(helper.success(), "the helper sent Ctrl+C to the CLI's console");
        let code = exit_code(&mut c);
        let err = err.join().unwrap();
        assert_eq!(code, 130, "{err}");
        assert!(err.contains("stub: cancelled"), "{err}");
    }

    fn a_second_ctrl_break_ends_the_run_and_its_runner() {
        let (mut c, rx, err) = cli("ignore", CREATE_NEW_PROCESS_GROUP);
        let stub = ready(&rx);
        // SAFETY: as above
        assert!(unsafe { GenerateConsoleCtrlEvent(CTRL_BREAK_EVENT, c.id()) } != 0);
        line(&rx, "stub: stop ignored");
        // SAFETY: as above
        assert!(unsafe { GenerateConsoleCtrlEvent(CTRL_BREAK_EVENT, c.id()) } != 0);
        assert_eq!(exit_code(&mut c), 143, "a second Ctrl+Break ends the CLI at once: {}", err.join().unwrap());
        let end = Instant::now() + Duration::from_secs(5);
        // loop: SERIAL-REQUIRED — a 50 ms poll [bounded: 5 s]
        while ck_core::proc::pid_alive(stub) && Instant::now() < end {
            std::thread::sleep(Duration::from_millis(50));
        }
        assert!(!ck_core::proc::pid_alive(stub), "the runner outlived the CLI (its job object should end it)");
    }
}
